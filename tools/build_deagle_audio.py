"""Build the Desert Eagle's independent game SFX from the project's credited CC0 recordings.
The original weapon files are read only. Run after build_sfx.py, or on its own:
    python tools/build_deagle_audio.py
Requires NumPy and FFmpeg. Peak-normalizes each finished clip, keeping gameplay mix headroom.
"""
from pathlib import Path
import subprocess,io,wave,json
import numpy as np
ROOT=Path(__file__).resolve().parents[1]
AUDIO=ROOT/'public/audio';SR=44100
def read(name,af='anull',start=0,duration=None):
 cmd=['ffmpeg','-v','error','-ss',str(start),'-i',str(AUDIO/(name+'.mp3'))]
 if duration:cmd+=['-t',str(duration)]
 cmd+=['-af',af,'-f','f32le','-ar',str(SR),'-ac','1','pipe:1']
 return np.frombuffer(subprocess.check_output(cmd),dtype='<f4').copy()
clips={}
def write(name,x,peak=-3,sync=None):
 x=x.astype(np.float64)
 fade=min(len(x),int(.025*SR));x[-fade:]*=np.linspace(1,0,fade)
 x[:min(35,len(x))]*=np.linspace(0,1,min(35,len(x)))
 x*=10**(peak/20)/max(.0001,np.max(np.abs(x)))
 if sync is None:
  power=np.convolve(x*x,np.ones(220)/220,mode='valid')
  sync=np.argmax(power)/SR
 proc=subprocess.run(['ffmpeg','-v','error','-y','-f','f32le','-ar',str(SR),'-ac','1','-i','pipe:0',
 '-c:a','libmp3lame','-b:a','128k',str(AUDIO/(name+'.mp3'))],input=x.astype('<f4').tobytes(),check=True)
 clips[name]=[round(len(x)/SR,3),round(float(sync),3)]
def layer(dest,source,delay,gain):
 at=int(delay*SR);n=min(len(source),len(dest)-at)
 if n>0:dest[at:at+n]+=source[:n]*gain
for i,rate in enumerate([.84,.81,.87],1):
 x=np.zeros(int(.95*SR))
 crack=read('weapons/pistol_fire_'+str(i),f'asetrate=44100*{rate},aresample=44100,highpass=f=65,lowpass=f=8800')
 body=read('weapons/ak_fire_'+str(i),'lowpass=f=240,highpass=f=45',duration=.28)
 metal=read('weapons/pistol_slide','highpass=f=700,lowpass=f=5000',start=.20,duration=.10)
 layer(x,crack,0,.82);layer(x,body,.002,.25);layer(x,metal,.065,.10)
 t=np.arange(len(x))/SR
 x+=.12*np.sin(2*np.pi*92*t)*np.exp(-t*25)*(1-np.exp(-t*450))
 write('weapons/deagle_fire_'+str(i),x,peak=-2.5,sync=0)
for name,source,rate,peak in [
 ('deagle_mag_out','pistol_mag_out',.90,-5),('deagle_mag_in','pistol_mag_in',.86,-4),
 ('deagle_slide','pistol_slide',.86,-3),('equip_deagle','equip_pistol',.91,-9)]:
 x=read('weapons/'+source,f'asetrate=44100*{rate},aresample=44100,highpass=f=60,lowpass=f=8000')
 write('weapons/'+name,x,peak=peak)
(ROOT/'src/desert-eagle-audio-clips.js').write_text(
 '// Generated by tools/build_deagle_audio.py. [duration, animation sync] in seconds.\n'+
 'export const eagleClips = '+json.dumps(clips,indent=2)+';\n',encoding='utf8')
print(json.dumps(clips,indent=2))
