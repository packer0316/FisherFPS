"""Derive three game rifle sound sets from the project's existing CC0 audio library.
Run independently: python tools/build_classic_rifle_audio.py (NumPy, FFmpeg).
"""
from pathlib import Path
import subprocess,json
import numpy as np
ROOT=Path(__file__).resolve().parents[1];AUDIO=ROOT/'public/audio';SR=44100;clips={}
def read(name,filters):
 return np.frombuffer(subprocess.check_output(['ffmpeg','-v','error','-i',str(AUDIO/(name+'.mp3')),'-af',filters,'-f','f32le','-ar',str(SR),'-ac','1','pipe:1']),dtype='<f4').copy()
def write(name,x,sync=0):
 x=x.astype(np.float64);x*=.67/max(np.max(np.abs(x)),.001)
 fade=min(int(.025*SR),len(x));x[-fade:]*=np.linspace(1,0,fade)
 subprocess.run(['ffmpeg','-v','error','-y','-f','f32le','-ar',str(SR),'-ac','1','-i','pipe:0','-c:a','libmp3lame','-b:a','128k',str(AUDIO/(name+'.mp3'))],input=x.astype('<f4').tobytes(),check=True)
 clips[name]=[round(len(x)/SR,3),round(sync,3)]
for name,rate,filters in [('m4a1',1.12,'highpass=f=100,lowpass=f=9000'),('scarl',.92,'highpass=f=65,lowpass=f=6800'),('vss',.88,'highpass=f=170,lowpass=f=1800')]:
 for i in range(1,4):
  x=read('weapons/ak_fire_'+str(i),f'asetrate=44100*{rate},aresample=44100,'+filters)
  if name=='vss':x=x[:int(SR*.24)]*np.exp(-np.arange(min(len(x),int(SR*.24)))/SR*7)
  write('weapons/'+name+'_fire_'+str(i),x)
(ROOT/'src/classic-rifle-audio-clips.js').write_text('// Generated by tools/build_classic_rifle_audio.py. [duration, sync] seconds.\nexport const rifleClips = '+json.dumps(clips,indent=2)+';\n',encoding='utf8')
print('Built',len(clips),'rifle clips')
